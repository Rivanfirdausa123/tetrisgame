const Glyph* glyph(char c)
{
    if (c >= 'a' && c <= 'z') {
        c = static_cast<char>(c - 'a' + 'A');
    }
    if (c >= 'A' && c <= 'Z') {
        return &kLetters[c - 'A'];
    }
    if (c >= '0' && c <= '9') {
        return &kDigits[c - '0'];
    }
    switch (c) {
    case ':': return &kColon;
    case '-': return &kDash;
    case '.': return &kDot;
    case '!': return &kBang;
    case '/': return &kSlash;
    case '+': return &kPlus;
    case '<': return &kLess;
    case '>': return &kGreater;
    default: return nullptr;
    }
}

